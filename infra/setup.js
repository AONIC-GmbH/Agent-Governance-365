async function askText(rl, label, def) {
  const hint = def === "" ? "" : ` [${def}]`;
  const raw = (await rl.question(`${label}${hint}: `)).trim();
  return raw === "" ? def : raw;
}

async function askYesNo(rl, label, defYes) {
  const hint = defYes ? "Y/n" : "y/N";
  const raw = (await rl.question(`${label} [${hint}]: `)).trim().toLowerCase();
  if (raw === "") return defYes;
  return raw === "y" || raw === "yes";
}

async function askChoice(rl, title, options, defaultIndex) {
  console.log(`\n${title}`);
  options.forEach((opt, i) => {
    const n = String(i + 1).padStart(2, " ");
    const rec = i === defaultIndex ? "  ← recommended" : "";
    console.log(` ${n}) ${opt.label}${rec}`);
    if (opt.note) console.log(`       ${opt.note}`);
  });
  const raw = (await rl.question(`Choose [${defaultIndex + 1}]: `)).trim();
  if (raw === "") return options[defaultIndex];
  const idx = Number.parseInt(raw, 10);
  if (!Number.isFinite(idx) || idx < 1 || idx > options.length) {
    console.log(`  (invalid choice, using ${options[defaultIndex].label})`);
    return options[defaultIndex];
  }
  return options[idx - 1];
}

function namesFor(style, prefix, environment, suffix) {
  const dash = suffix ? `-${suffix}` : "";
  if (style === "current") {
    return {
      resource_group_name: CURRENT.resourceGroup,
      api_name: CURRENT.api,
      web_name: CURRENT.web,
      postgres_name: CURRENT.postgres,
      key_vault_name: CURRENT.keyVault,
      prefix: CURRENT.prefix,
      name_suffix: "",
    };
  }
  const kv = `${prefix}-kv-${environment}${dash}`.replace(/_/g, "-");
  return {
    resource_group_name: `rg-${prefix}-${environment}`,
    api_name: `${prefix}-api${dash}`,
    web_name: `${prefix}-web${dash}`,
    postgres_name: `${prefix}-pg-${environment}${dash}`,
    key_vault_name: kv.length <= 24 ? kv : kv.replace(/-/g, "").slice(0, 24),
    prefix,
    name_suffix: suffix,
  };
}


#!/usr/bin/env node
/**
 * Interactive generator for infra/terraform/terraform.tfvars
 *
 * Defaults follow the current hosted Runpipe layout (Linux App Service Node 22,
 * Static Web App, Postgres Flexible Server, Key Vault). Each prompt also lists
 * other SKUs / regions / network modes that are feasible for this stack.
 *
 * Usage:
 *   npm run setup:azure
 *   node infra/setup.js --yes
 *   node infra/setup.js --help
 */

const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const readline = require("node:readline/promises");
const { stdin: input, stdout: output } = require("node:process");

const ROOT = path.resolve(__dirname, "..");
const TF_DIR = path.join(__dirname, "terraform");
const TFVARS = path.join(TF_DIR, "terraform.tfvars");
const EXAMPLE = path.join(TF_DIR, "terraform.tfvars.example");

const SWA_REGIONS = new Set([
  "westeurope",
  "eastus2",
  "centralus",
  "westus2",
  "eastasia",
  "canadacentral",
]);

const CURRENT = {
  resourceGroup: "rg-runpipe-dev-2",
  api: "runpipe2-api",
  web: "runpipe2-web",
  postgres: "runpipe2-pg-dev",
  keyVault: "runpipe2-kv-dev",
  prefix: "runpipe2",
};

function parseArgs(argv) {
  const args = { yes: false, help: false, overwrite: false };
  for (const a of argv.slice(2)) {
    if (a === "--yes" || a === "-y") args.yes = true;
    else if (a === "--help" || a === "-h") args.help = true;
    else if (a === "--overwrite") args.overwrite = true;
    else {
      console.error(`Unknown argument: ${a}`);
      args.help = true;
    }
  }
  return args;
}

function help() {
  console.log(`
Runpipe Azure Terraform setup

Generates ${path.relative(ROOT, TFVARS)} for the Terraform in infra/terraform/.

  npm run setup:azure          Interactive (recommended)
  npm run setup:azure -- --yes Accept recommended values (new unique names)
  node infra/setup.js --help

Then:
  cd infra/terraform
  terraform init
  terraform plan
  terraform apply
`);
}

function tryAz(args) {
  const bins = process.platform === "win32" ? ["az.cmd", "az.exe", "az"] : ["az"];
  for (const bin of bins) {
    try {
      return execFileSync(bin, args, {
        encoding: "utf8",
        timeout: 4000,
        windowsHide: true,
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
    } catch {
      // try next binary
    }
  }
  return "";
}

async function publicIp() {
  const ac = new AbortController();
  const timer = setTimeout(() => ac.abort(), 4000);
  try {
    const res = await fetch("https://api.ipify.org?format=json", { signal: ac.signal });
    if (!res.ok) return "";
    const body = await res.json();
    return String(body.ip || "");
  } catch {
    return "";
  } finally {
    clearTimeout(timer);
  }
}

function randomSuffix() {
  const alphabet = "abcdefghijklmnopqrstuvwxyz0123456789";
  let s = "";
  for (let i = 0; i < 4; i++) s += alphabet[Math.floor(Math.random() * alphabet.length)];
  return s;
}

function hclString(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function hclBool(value) {
  return value ? "true" : "false";
}

